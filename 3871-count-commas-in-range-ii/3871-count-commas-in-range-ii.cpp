class Solution {
public:
    long long countCommas(long long n) {
        if (n < 1000)
            return 0;

        long long count = 0;

        if (n < 1000000) {
            count = n - 999;
        }
        else if (n < 1000000000) {
            count = (999999 - 999) + (n - 999999) * 2;
        }
        else if (n < 1000000000000LL) {
            count = (999999 - 999) 
                  + (999999999 - 999999) * 2
                  + (n - 999999999) * 3;
        }
        else if (n < 1000000000000000LL) {
            count = (999999 - 999)
                  + (999999999 - 999999) * 2
                  + (999999999999LL - 999999999) * 3
                  + (n - 999999999999LL) * 4;
        }
        else {
            count = (999999 - 999)
                  + (999999999 - 999999) * 2
                  + (999999999999LL - 999999999) * 3
                  + (999999999999999LL - 999999999999LL) * 4
                  + (n - 999999999999999LL) * 5;
        }

        return count;
    }
};